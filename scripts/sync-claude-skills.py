#!/usr/bin/env python3
"""Generate native Claude/Codewhale skills from AI Berkshire slash-command sources.

`skills/*.md` are Claude Code slash commands: flat markdown files that use the
`$ARGUMENTS` placeholder. Skill-aware agents (Claude Code, Codewhale, Cursor)
discover skills as `<skill-dir>/SKILL.md` with YAML frontmatter, so the same
workflow needs a thin adapter wrapper to become loadable as a skill.

This script generates that wrapper. The source file stays the single source of
truth for the workflow prose; the generated SKILL.md only adds frontmatter and
an adapter note. Do not edit generated files by hand.

Usage:
    python scripts/sync-claude-skills.py             # (re)generate all skills
    python scripts/sync-claude-skills.py --check      # CI check, writes nothing
    python scripts/sync-claude-skills.py --show NAME  # print one generated skill
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

# Source workflows contain emoji; Windows console defaults to a legacy codec.
if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")

ROOT = Path(__file__).resolve().parents[1]
SOURCE_DIR = ROOT / "skills"
TARGET_DIR = ROOT / ".claude" / "skills"

ADAPTER_NOTE = """\
<!-- Generated by scripts/sync-claude-skills.py from skills/{source}. Do not edit. -->
<!-- Edit the source workflow instead, then re-run the script. -->

## 使用说明（由 Claude Code 斜杠命令适配）

本技能与 `skills/{source}` 是同一套工作流，源文件是唯一事实来源。

- 源文件里的 `$ARGUMENTS` 指本轮用户请求中要处理的对象（公司名、股票代码、行业、期间等）。
- 源文件提到的 Claude Code 专用工具，在本会话中按下列对应关系执行：
  - `Task` / Agent → `agent` 工具（可并行启动多个子智能体）
  - `Read` / `Write` / `Bash` → `read` / `write` / `bash`
  - 联网检索或抓取（WebSearch 等）→ 会话实际可用的联网能力；不可用时明确标注数据缺口，不得编造数据
- 仓库共享工具优先用命令行调用，例如 `python3 tools/financial_rigor.py ...`、`python3 tools/report_audit.py ...`。
- 研究开始前先运行 `date` 确认当天日期，并在报告头部标注数据截止日期。
- 遵守 `AGENTS.md` / `CLAUDE.md` 的研究质量规则：多源交叉验证、精确算术、清楚标注不确定性。

---

"""


def split_frontmatter(text: str) -> tuple[str | None, str]:
    """Split a leading YAML frontmatter block off the body, if present."""
    if not text.startswith("---\n"):
        return None, text
    end = text.find("\n---\n", 4)
    if end == -1:
        return None, text
    return text[4:end], text[end + 5 :].lstrip("\n")


def first_heading(text: str, fallback: str) -> str:
    for line in text.splitlines():
        if line.startswith("# "):
            return line[2:].strip()
    return fallback


def yaml_quote(value: str) -> str:
    value = value.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{value}"'


def unquote(value: str) -> str:
    value = value.strip()
    if len(value) >= 2 and value[0] == value[-1] and value[0] in {'"', "'"}:
        return value[1:-1]
    return value


def description_for(name: str, source_name: str, source_text: str) -> str:
    """Reuse the source description when it exists; otherwise derive one.

    The description drives skill routing, so a source file that already ships a
    hand-written trigger description (frontmatter `description:`) wins.
    """
    existing, body = split_frontmatter(source_text)
    if existing:
        match = re.search(r"(?m)^description:\s*(.+)$", existing)
        if match:
            return unquote(match.group(1))
    title = first_heading(body, name)
    return f"{title}。（AI Berkshire 工作流，源：skills/{source_name}）"


def render(name: str, source_name: str, source_text: str) -> str:
    _, body = split_frontmatter(source_text)
    frontmatter = (
        "---\n"
        f"name: {name}\n"
        f"description: {yaml_quote(description_for(name, source_name, source_text))}\n"
        "---\n\n"
    )
    note = ADAPTER_NOTE.format(source=source_name)
    return frontmatter + note + body.rstrip() + "\n"


def main() -> None:
    args = sys.argv[1:]
    check = "--check" in args
    show: str | None = None
    rest: list[str] = []
    i = 0
    while i < len(args):
        if args[i] == "--show":
            if i + 1 >= len(args):
                raise SystemExit("--show requires a skill name")
            show = args[i + 1]
            i += 2
            continue
        rest.append(args[i])
        i += 1

    unknown = [a for a in rest if a != "--check"]
    if unknown:
        raise SystemExit(f"Unknown argument(s): {', '.join(unknown)}")

    if show is not None:
        source = SOURCE_DIR / f"{show}.md"
        if not source.exists():
            raise SystemExit(f"No such source workflow: {source.relative_to(ROOT)}")
        sys.stdout.write(render(show, source.name, source.read_text(encoding="utf-8")))
        return

    if not check:
        TARGET_DIR.mkdir(parents=True, exist_ok=True)

    count = 0
    stale: list[str] = []
    for source in sorted(SOURCE_DIR.glob("*.md")):
        name = source.stem
        content = render(name, source.name, source.read_text(encoding="utf-8"))
        target = TARGET_DIR / name / "SKILL.md"
        if check:
            if not target.exists() or target.read_text(encoding="utf-8") != content:
                stale.append(str(target.relative_to(ROOT)))
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content, encoding="utf-8")
        count += 1

    if check:
        if stale:
            print("Claude skills are out of date:")
            for path in stale:
                print(f"  {path}")
            raise SystemExit(1)
        print(f"Checked {count} Claude skills in {TARGET_DIR.relative_to(ROOT)}")
        return

    print(f"Generated {count} Claude skills in {TARGET_DIR.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
